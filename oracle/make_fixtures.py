"""Regenerate the pandoc fixtures and check fixture provenance.

    make_fixtures.py             regenerate tests/fixtures/pandoc/*.docx from tests/fixtures/sources/*.md
    make_fixtures.py --check     fail if a committed pandoc fixture differs from regeneration,
                                 or if any fixture lacks a provenance entry (or vice versa)
    make_fixtures.py --libreoffice
                                 round-trip every pandoc fixture through LibreOffice into
                                 tests/fixtures/libreoffice/; a maintainer task, version-dependent

pandoc is byte-deterministic under SOURCE_DATE_EPOCH, so the pandoc fixtures
are regenerable in CI. LibreOffice output depends on its version, so those
fixtures are committed with the version recorded in provenance.json and are
not regenerated by `--check`, nor are the Word fixtures that
make_word_fixtures.py produces or the Google Docs fixtures that
scrub_gdocs_fixture.py prepares.
"""

import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "tests" / "fixtures"
SOURCES = FIXTURES / "sources"
PANDOC_OUT = FIXTURES / "pandoc"
LIBREOFFICE_OUT = FIXTURES / "libreoffice"
PROVENANCE = FIXTURES / "provenance.json"
EPOCH = "1700000000"


def pandoc_binary():
    return os.environ.get("PANDOC") or shutil.which("pandoc") or sys.exit("pandoc not found: set PANDOC or run through blueprint")


def soffice_binary():
    candidates = [os.environ.get("SOFFICE"), shutil.which("soffice"), shutil.which("libreoffice"),
                  "/Applications/LibreOffice.app/Contents/MacOS/soffice"]
    for candidate in candidates:
        if candidate and pathlib.Path(candidate).exists():
            return candidate
    sys.exit("LibreOffice not found: set SOFFICE")


def render(source, out_dir):
    out = out_dir / (source.stem + ".docx")
    env = dict(os.environ, SOURCE_DATE_EPOCH=EPOCH)
    subprocess.run([pandoc_binary(), str(source), "-o", str(out)], check=True, env=env)
    return out


def regenerate():
    PANDOC_OUT.mkdir(parents=True, exist_ok=True)
    for source in sorted(SOURCES.glob("*.md")):
        out = render(source, PANDOC_OUT)
        print(f"wrote {out.relative_to(ROOT)}")


def check():
    failures = []
    with tempfile.TemporaryDirectory() as tmp:
        for source in sorted(SOURCES.glob("*.md")):
            fresh = render(source, pathlib.Path(tmp))
            committed = PANDOC_OUT / fresh.name
            if not committed.exists():
                failures.append(f"{committed.relative_to(ROOT)}: missing; run make_fixtures.py")
            elif committed.read_bytes() != fresh.read_bytes():
                failures.append(f"{committed.relative_to(ROOT)}: differs from regeneration")
    provenance = json.loads(PROVENANCE.read_text()) if PROVENANCE.exists() else {"fixtures": {}}
    recorded = set(provenance.get("fixtures", {}))
    present = {str(p.relative_to(FIXTURES)) for p in FIXTURES.rglob("*.docx")}
    for missing in sorted(present - recorded):
        failures.append(f"{missing}: no provenance entry")
    for stale in sorted(recorded - present):
        failures.append(f"{stale}: provenance entry without a file")
    for entry, record in provenance.get("fixtures", {}).items():
        for key in ("producer", "version", "produced_on", "source", "purpose"):
            if not record.get(key):
                failures.append(f"{entry}: provenance lacks {key}")
    for failure in failures:
        print(f"FAIL {failure}")
    print(f"checked {len(present)} fixtures, {len(failures)} failures")
    return 1 if failures else 0


def libreoffice_roundtrip():
    soffice = soffice_binary()
    LIBREOFFICE_OUT.mkdir(parents=True, exist_ok=True)
    version = subprocess.run([soffice, "--version"], capture_output=True, text=True, check=True).stdout.strip()
    print(version)
    with tempfile.TemporaryDirectory() as profile:
        for fixture in sorted(PANDOC_OUT.glob("*.docx")):
            subprocess.run([soffice, f"-env:UserInstallation=file://{profile}", "--headless", "--norestore",
                            "--convert-to", "docx:MS Word 2007 XML", "--outdir", str(LIBREOFFICE_OUT), str(fixture)],
                           check=True, capture_output=True)
            print(f"wrote {(LIBREOFFICE_OUT / fixture.name).relative_to(ROOT)}")
    print("record the version above in tests/fixtures/provenance.json")


if __name__ == "__main__":
    args = sys.argv[1:]
    if args == ["--check"]:
        sys.exit(check())
    if args == ["--libreoffice"]:
        libreoffice_roundtrip()
    elif args == []:
        regenerate()
    else:
        sys.exit(__doc__)
